"""Generate the demo configs from the full-run configs.

Each model/configs/full_run_*.yaml covers NSW, QLD, SA and VIC for 2021-2025
and needs the EDP cohort. Its demo counterpart, model/configs/demo/<same
name>.yaml, is a copy with the `states:` and `years:` lines replaced so that
it runs on the sample household H0001 (NSW, 2022-2024). Everything else,
including `name:`, is unchanged, so a demo run writes to the same
data/output/runs/<name>/ folder that the analysis scripts read.

The copy is textual so comments and layout are kept. Tariff maps for the
other states and years stay in the file and are ignored for scenarios that
are not run.

Run from the project root:

    python3 -m model.scripts.make_demo_configs

Existing demo configs are overwritten.
"""
import re
from pathlib import Path

CONFIG_DIR = Path('model/configs')
DEMO_DIR = CONFIG_DIR / 'demo'
DEMO_STATES = '[NSW]'
DEMO_YEARS = '[2022, 2023, 2024]'
HEADER = (
    '# Demo version of model/configs/{name}, generated by\n'
    '# model/scripts/make_demo_configs.py. Runs the sample household H0001\n'
    '# for states {states} and years {years}. Only the states: and years:\n'
    '# settings differ from the full run.\n'
    '#\n'
)

STATES_RE = re.compile(r'^states:.*$', re.MULTILINE)
YEARS_RE = re.compile(r'^years:.*$', re.MULTILINE)


def make_demo(text: str, name: str) -> str:
    if len(STATES_RE.findall(text)) != 1 or len(YEARS_RE.findall(text)) != 1:
        raise ValueError(f"{name}: expected exactly one 'states:' and one 'years:' line")
    text = STATES_RE.sub(f'states: {DEMO_STATES}', text)
    text = YEARS_RE.sub(f'years: {DEMO_YEARS}', text)
    text = text.replace(f'model/configs/{name}', f'model/configs/demo/{name}')
    return HEADER.format(name=name, states=DEMO_STATES, years=DEMO_YEARS) + text


def main() -> None:
    DEMO_DIR.mkdir(exist_ok=True)
    sources = sorted(CONFIG_DIR.glob('full_run_*.yaml'))
    for src in sources:
        (DEMO_DIR / src.name).write_text(make_demo(src.read_text(), src.name))
    print(f"Wrote {len(sources)} demo configs to {DEMO_DIR}/")


if __name__ == '__main__':
    main()
